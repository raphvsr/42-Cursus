#include "../../philosopher.h"

long	ft_atol(char *str)
{
	int		i;
	long	res;

	res = 0;
	i = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == ' ')
		i++;
	if (str[i] == '+')
		i++;
	while (str[i] >= '0' && str[i] <= '9')
	{
		res = res * 10 + (str[i] - '0');
		if (res > 2147483647)
			return (2147483648L);
		i++;
	}
	return (res);
}
